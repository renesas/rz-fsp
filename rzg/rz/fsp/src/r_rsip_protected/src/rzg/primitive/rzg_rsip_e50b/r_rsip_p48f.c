rsip_ret_t r_rsip_p48f (void)
{
    RSIP_PRV_PRIMITIVE_ENTRY;
    uint32_t iLoop;
    uint32_t jLoop;
    uint32_t kLoop;
    uint32_t oLoop;
    uint32_t oLoop1;
    uint32_t OFS_ADR;
    (void) iLoop;
    (void) jLoop;
    (void) kLoop;
    (void) oLoop;
    (void) oLoop1;
    (void) OFS_ADR;
    if (0x00000000U == RD1_MASK(REG_1440H, 0xffffffffU))
    {
        r_rsip_func101(bswap_32big(0x74b8aa85U), bswap_32big(0x9a0b14a0U), bswap_32big(0xc1f724b7U),
                       bswap_32big(0x1979b6f8U));
    }
    else if (0x00000001U == RD1_MASK(REG_1440H, 0xffffffffU))
    {
        r_rsip_func101(bswap_32big(0x322c6191U), bswap_32big(0xad82b90eU), bswap_32big(0xfbe67311U),
                       bswap_32big(0x7ec8f654U));
    }
    else if (0x00000002U == RD1_MASK(REG_1440H, 0xffffffffU))
    {
        r_rsip_func101(bswap_32big(0x7d097659U), bswap_32big(0x7a22d433U), bswap_32big(0x1de017ccU),
                       bswap_32big(0x1dc7e433U));
    }
    else if (0x00000003U == RD1_MASK(REG_1440H, 0xffffffffU))
    {
        r_rsip_func101(bswap_32big(0xd5926bc3U), bswap_32big(0x6c9d2db8U), bswap_32big(0x1adf9b10U),
                       bswap_32big(0x2374d27eU));
    }
    else if (0x00000004U == RD1_MASK(REG_1440H, 0xffffffffU))
    {
        r_rsip_func101(bswap_32big(0xe7162f38U), bswap_32big(0x6b682befU), bswap_32big(0xbd7c3e3aU),
                       bswap_32big(0x10f14fb4U));
    }

    r_rsip_func102(bswap_32big(0xb2b21488U),
                   bswap_32big(0xa29a5c05U),
                   bswap_32big(0xd3d5b244U),
                   bswap_32big(0x72d12888U));
    WR1_PROG(REG_14BCH, 0x00000040U);
    WAIT_STS(REG_142CH, 12U, 0U);

    return RSIP_RET_PASS;
}
