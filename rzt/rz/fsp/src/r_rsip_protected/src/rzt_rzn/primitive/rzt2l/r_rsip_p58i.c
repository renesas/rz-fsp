        WR1_PROG(REG_1458H, 0x00000000U);
        WR1_PROG(REG_1600H, 0x00000022U);
        WR1_PROG(REG_1458H, 0x00000000U);
        r_rsip_func101(bswap_32big(0xb5c378d6U), bswap_32big(0x69c6aee9U), bswap_32big(0xc3713d26U),
                       bswap_32big(0x14ff4198U));
